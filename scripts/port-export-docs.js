// Copies the document half of the Export Docs Builder into the dealer
// portal, so the pallet screen makes the customs paperwork with exactly the
// app's own rules, wording and layout.
//
//   node scripts/port-export-docs.js
//
// Reads tools-site/exportdocs/index.html (the latest export documents app
// in the repo) and rewrites the block between the EXPORT DOCS markers in
// dealer-portal/index.html. Run it again whenever the export app changes.
//
// What is taken: the classification rules, the discount and charge
// spreading, the line merging, the Lacey weights, the three documents
// (proforma, Lacey PPQ 505, TSCA), the sheet styles and the logo. What is
// left behind: reading QuickBooks PDFs, which the portal does not need
// because it already has the invoice lines. Field reads like
// $("shipVia").value become F.shipVia, and the app's state becomes S.

const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const APP = fs.readFileSync(path.join(ROOT, 'tools-site/exportdocs/index.html'), 'utf8');
const PORTAL = path.join(ROOT, 'dealer-portal/index.html');

const fn = name => {
  const i = APP.indexOf('\nfunction ' + name + '(');
  if (i < 0) throw new Error('export app has no function ' + name);
  const j = APP.indexOf('\n}\n', i);
  return APP.slice(i + 1, j + 2);
};
const konst = name => {
  const m = APP.match(new RegExp('\\nconst ' + name + ' =[\\s\\S]*?;\\n'));
  if (!m) throw new Error('export app has no const ' + name);
  return m[0].trim();
};

/* the defaults of every field the documents read, off the app's own form */
const F = {};
const form = APP.slice(APP.indexOf('<body'), APP.indexOf('<script', APP.indexOf('<body')));
for (const m of form.matchAll(/<input[^>]*id="(\w+)"[^>]*>/g)) {
  const tag = m[0], id = m[1];
  if (/type="checkbox"/.test(tag)) F[id] = /\schecked/.test(tag);
  else { const v = tag.match(/value="([^"]*)"/); F[id] = v ? v[1].replace(/&amp;/g, '&') : ''; }
}
for (const m of form.matchAll(/<select id="(\w+)">\s*<option value="([^"]*)"/g)) F[m[1]] = m[2];
for (const m of form.matchAll(/<textarea id="(\w+)"[^>]*>([^<]*)<\/textarea>/g)) F[m[1]] = m[2];

const NAMES = ['wordRe', 'classifyLabel', 'ruleFor', 'applyRules', 'spreadValue', 'rebuildLines',
  'mergeLines', 'activeLines', 'totals', 'palletTareLbs', 'netShipmentLbs', 'hsGroups',
  'docProforma', 'docLacey', 'tscaDescriptions', 'docTsca', 'firstLine', 'secondLine',
  'restLines', 'addrOneLine', 'sheetWrap', 'roundTo', 'usDate', 'intfmt', 'money', 'parseNum'];
let code = NAMES.map(fn).join('\n');
code = code
  .replace(/\$\("(\w+)"\)\.value/g, 'F.$1')
  .replace(/\$\("(\w+)"\)\.checked/g, 'F.$1')
  .replace(/\bstate\./g, 'S.')
  /* the TSCA function also shows and hides two of the app's own boxes */
  .replace(/^\s*\$\("tsca\w+Wrap"\)\.style\.display.*\n/gm, '');
if (/\$\(/.test(code)) throw new Error('a field read was not converted: ' + code.match(/.{40}\$\(.{40}/)[0]);

const comps = APP.match(/comps: (\[[\s\S]*?\])/)[1];
const css = APP.slice(APP.indexOf('.sheetscale{margin-bottom'), APP.indexOf('</style>'));
const doc = (APP.match(/--doc:([^;]+);/) || [])[1];

const block =
`/* ==== EXPORT DOCS: generated by scripts/port-export-docs.js from
   tools-site/exportdocs/index.html. Do not edit by hand; change the export
   app and run the script again. ==== */
const EXPDOC = (() => {
  ${konst('LOGO_SRC')}
  ${konst('DEFAULT_EXPORTER')}
  ${konst('DEFAULT_IMPORTER')}
  ${konst('RULES_SEED')}
  ${konst('CI_ROWS_PER_PAGE')}
  const COMPS = ${comps};
  const FIELDS = Object.assign(${JSON.stringify(F)},
    {exporter: DEFAULT_EXPORTER, importer: DEFAULT_IMPORTER});
  const CSS = ${JSON.stringify(':root{--doc:' + doc + ';--pv:1}\n' + css)};
  const esc = (s) => String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const nl2br = (s) => esc(s).replace(/\\n/g, "<br>");
  let F = null, S = null;
${code}
  /* files: one per invoice, {name, lines:[{item, desc, rawDesc, qty, unit,
     amount, hs, hsFromSource, src, keep}], extras: []}, as the app's own
     PDF reader would have left them */
  function build(fields, files){
    F = Object.assign({}, FIELDS, fields || {});
    S = {files: files, lines: [], rules: RULES_SEED.map(r => Object.assign({}, r)),
         comps: COMPS.map(c => Object.assign({}, c))};
    rebuildLines();
    return {sheets: docProforma() + docLacey() + docTsca(), totals: totals(),
            lbs: hsGroups().reduce((s, g) => s + g.rows.reduce((a, r) => a + r.qtyLbs, 0), 0)};
  }
  return {FIELDS: FIELDS, CSS: CSS, build: build};
})();
/* ==== END EXPORT DOCS ==== */`;

let portal = fs.readFileSync(PORTAL, 'utf8');
const a = portal.indexOf('/* ==== EXPORT DOCS:'), b = portal.indexOf('/* ==== END EXPORT DOCS ==== */');
if (a < 0 || b < 0) throw new Error('the portal has no EXPORT DOCS markers');
portal = portal.slice(0, a) + block + portal.slice(b + '/* ==== END EXPORT DOCS ==== */'.length);
fs.writeFileSync(PORTAL, portal);
console.log('export docs block written:', block.length, 'characters, fields:', Object.keys(F).length);
